package domain;

/**
 * Підраховує кількість "щасливих" трамвайних квитків.
 * Шестизначний квиток (000000–999999) вважається щасливим,
 * якщо сума перших трьох цифр дорівнює сумі останніх трьох цифр.
 */
public class Exercise {

    /**
     * Підраховує всі щасливі квитки в діапазоні від 000000 до 999999.
     *
     * @return загальна кількість щасливих шестизначних квитків
     */
    public static int calculate() {
        int кількість = 0;
        for (int квиток = 0; квиток <= 999999; квиток++) {
            if (єЩасливим(квиток)) {
                кількість++;
            }
        }
        return кількість;
    }

    /**
     * Перевіряє чи є даний номер квитка щасливим.
     *
     * @param квиток число від 0 до 999999, що представляє шестизначний квиток
     * @return true якщо сума перших трьох цифр дорівнює сумі останніх трьох
     */
    private static boolean єЩасливим(int квиток) {
        int першаСума  = квиток / 100000 + (квиток / 10000 % 10) + (квиток / 1000 % 10);
        int другаСума = квиток / 100 % 10 + (квиток / 10 % 10) + (квиток % 10);
        return першаСума == другаСума;
    }
}
